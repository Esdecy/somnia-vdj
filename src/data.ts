export function loadDreams(): Dream[] {
  const saved = localStorage.getItem("SOMNIA_DREAMS");
  if (saved) {
    try {
      return JSON.parse(saved);
    } catch (e) {
      console.error("Failed to parse dreams, recreating defaults", e);
    }
  }
  return PRESET_DREAMS;
}

export function saveDreams(dreams: Dream[]): void {
  localStorage.setItem("SOMNIA_DREAMS", JSON.stringify(dreams));
}

